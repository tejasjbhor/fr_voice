_TTS_REPLACE = {
    "BP":    "बी पी",
    "Sugar": "शुगर",
    "mg":    "मिलिग्राम",
    "dL":    "डेसीलिटर",
    "HR":    "हार्ट रेट",
    "112":   "एकशे बारा",
    "108":   "एकशे आठ",
    "102":   "एकशे दोन",
    "SPO2":  "ऑक्सिजन",
}

_PROSODY_PATTERNS = [
    (_re.compile(r"(हं)\.\.\.\s*"),   r"\1... "),
    (_re.compile(r"(बरं)\.\.\.\s*"),  r"\1... "),
    (_re.compile(r"(अरे)\.\.\.\s*"),  r"\1... "),
    (_re.compile(r"\bधन्यवाद सांगितल्याबद्दल\b"), "बरं झालं सांगितलं"),
    (_re.compile(r"\s+"), " "),
]


# ── Honorific safety net ──────────────────────────────────────────
# The persona is written addressing Sathi as "तू", so the model sometimes
# mirrors that back at the patient — "तुझी तब्येत" instead of "तुमची तब्येत".
# The prompt now warns about this in three places, but a slip must never
# reach an elderly caller's ear, so we also repair it deterministically.
#
# Only the oblique/possessive forms are rewritten. Those are safe: the verb
# agrees with the subject, not with a dative or possessive, so "तुला बरं वाटतंय"
# → "तुम्हाला बरं वाटतंय" stays grammatical. A bare subject "तू" would need the
# verb changed too ("तू आहेस" → "तुम्ही आहात"), which a regex cannot do reliably,
# so that case is left to the prompt and reported by honorific_slips().

_HONORIFIC_FIXES = [
    ("तुझ्या",   "तुमच्या"),    # also covers तुझ्याकडे / तुझ्यासाठी / तुझ्यावर
    ("तुझी",     "तुमची"),
    ("तुझे",     "तुमचे"),
    ("तुझा",     "तुमचा"),
    ("तुझं",     "तुमचं"),
    ("तुझ्‍या",  "तुमच्या"),    # ZWJ variant STT/LLM sometimes emits
    ("तुला",     "तुम्हाला"),
]

# Bare "तू" as a standalone word — detected and logged, not auto-rewritten.
_BARE_TU = _re.compile(r"(?<![ऀ-ॿ])तू(?![ऀ-ॿ])")


def fix_honorifics(text: str) -> str:
    """Rewrite informal तू-forms aimed at the patient into respectful तुम्ही-forms."""
    for informal, respectful in _HONORIFIC_FIXES:
        text = text.replace(informal, respectful)
    return text


def honorific_slips(text: str) -> list:
    """Informal forms still present after fixing — for logging/monitoring."""
    slips = []
    for informal, _ in _HONORIFIC_FIXES:
        if informal in (text or ""):
            slips.append(informal)
    if _BARE_TU.search(text or ""):
        slips.append("तू")
    return slips


def prepare_for_tts(text: str) -> str:
    for abbr, spoken in _TTS_REPLACE.items():
        text = _re.sub(rf"\b{_re.escape(abbr)}\b", spoken, text)
    text = fix_honorifics(text)
    for pattern, replacement in _PROSODY_PATTERNS:
        text = pattern.sub(replacement, text)
    text = _re.sub(r"[*_~`#→•]", "", text)
    return text.strip()
