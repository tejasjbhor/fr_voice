def read_tone(text: str) -> str | None:
    t = (text or "").lower()
    if not t:
        return None
    for tone in ("emergency", "annoyed", "pain", "sad", "lonely",
                 "worried", "tired", "happy"):
        if any(kw in t for kw in _TONE_SIGNALS[tone]):
            return tone
    return None


