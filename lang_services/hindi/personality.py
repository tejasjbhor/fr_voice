_TTS_REPLACE = {
    "BP":    "बी पी",
    "Sugar": "शुगर",
    "mg":    "मिलीग्राम",
    "dL":    "डेसीलीटर",
    "HR":    "हार्ट रेट",
    "112":   "एक सौ बारह",
    "108":   "एक सौ आठ",
    "102":   "एक सौ दो",
    "SPO2":  "ऑक्सीजन",
}

_PROSODY_PATTERNS = [
    (_re.compile(r"(हाँ)\.\.\.\s*"),  r"\1... "),
    (_re.compile(r"(अरे)\.\.\.\s*"),  r"\1... "),
    (_re.compile(r"(हम्म)\.\.\.\s*"), r"\1... "),
    (_re.compile(r"(ओह)\.\.\.\s*"),   r"\1... "),
    (_re.compile(r"\bधन्यवाद बताने के लिए\b"), "अच्छा किया बताया"),
    (_re.compile(r"\s+"), " "),
]


# ── Honorific safety net ──────────────────────────────────────────
# Same problem as the Marathi pack: the persona addresses Sathi as "तुम", and
# the model can mirror that at the patient. Only oblique/possessive forms are
# rewritten — they don't require the verb to change, so the sentence stays
# grammatical. A bare subject "तुम" needs verb agreement too, so it is only
# reported (see honorific_slips) and left to the prompt.

_HONORIFIC_FIXES = [
    ("तुम्हारा", "आपका"),
    ("तुम्हारी", "आपकी"),
    ("तुम्हारे", "आपके"),
    ("तुम्हें",  "आपको"),
    ("तुमको",   "आपको"),
    ("तुमसे",   "आपसे"),
    ("तुम्हारा", "आपका"),
    ("तेरा",    "आपका"),
    ("तेरी",    "आपकी"),
    ("तेरे",    "आपके"),
    ("तुझे",    "आपको"),
    ("तुझको",   "आपको"),
    ("तुझसे",   "आपसे"),
]

_BARE_TUM = _re.compile(r"(?<![ऀ-ॿ])(?:तुम|तू)(?![ऀ-ॿ])")


def fix_honorifics(text: str) -> str:
    """Rewrite informal तुम-forms aimed at the patient into respectful आप-forms."""
    for informal, respectful in _HONORIFIC_FIXES:
        text = text.replace(informal, respectful)
    return text


def honorific_slips(text: str) -> list:
    """Informal forms still present after fixing — for logging/monitoring."""
    slips = [i for i, _ in _HONORIFIC_FIXES if i in (text or "")]
    if _BARE_TUM.search(text or ""):
        slips.append("तुम")
    return slips


def prepare_for_tts(text: str) -> str:
    for abbr, spoken in _TTS_REPLACE.items():
        text = _re.sub(rf"\b{_re.escape(abbr)}\b", spoken, text)
    text = fix_honorifics(text)
    for pattern, replacement in _PROSODY_PATTERNS:
        text = pattern.sub(replacement, text)
    text = _re.sub(r"[*_~`#→•]", "", text)
    return text.strip()
